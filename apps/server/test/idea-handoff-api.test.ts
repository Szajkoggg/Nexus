import { test } from "node:test";
import assert from "node:assert/strict";
import { once } from "node:events";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { createServer } from "node:net";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ProjectStore, writeRegistry, type IdeaHandoff, type SessionFile } from "@nexus/protocol";
import { spawnServer } from "./helpers.ts";
import { serverUp } from "./wait.ts";
const freePort = () => new Promise<number>((resolve) => {
  const server = createServer();
  server.listen(0, "127.0.0.1", () => { const port = (server.address() as { port: number }).port; server.close(() => resolve(port)); });
});

test("idea HTTP writes are guarded; chat opening is model-free and direct handoff survives duplicate requests and restart", async () => {
  const base = mkdtempSync(join(tmpdir(), "nexus-idea-onward-api-")), root = join(base, "p");
  process.env.NEXUS_HOME = join(base, "home");
  const here = dirname(fileURLToPath(import.meta.url));
  const fakeLog = join(base, "fake.log");
  const env = { NEXUS_CLAUDE: join(here, "fake-claude.ts"), NEXUS_CODEX: join(here, "fake-codex.ts"), FAKE_LOG: fakeLog, NEXUS_LOG: "" };
  mkdirSync(join(root, "notes"), { recursive: true });
  const store = ProjectStore.init(root, { id: "p", name: "P", root, orchestrator: { notify: false } });
  store.updateProject((p) => ({ ...p, conversations: { ...p.conversations, notes_dir: "notes" } }));
  const note = join(root, "notes/a.md"), original = "# A\n**Summary:** Summary.\n## Decided\n### 2026-11-14\n- Approved content.\n## Open\n- Unanswered?\n";
  writeFileSync(note, original);
  store.writeQueue({ protocol: 1, id: "HELD", title: "Held draft", revision: 1, status: "proposed", approvals: [], history: [], checks: [], stop_conditions: [], steps: [{ id: "H1", title: "Wait", goal: "Never start from a handoff", acceptance: [] }] });
  const queue = readFileSync(join(store.dir, "queues/HELD/queue.yaml"), "utf8");
  writeRegistry({ protocol: 1, projects: [{ id: "p", root }] });
  const port = await freePort(), url = `http://127.0.0.1:${port}`;
  let child = spawnServer({ ...env, NEXUS_PORT: String(port) });
  const post = (path: string, body: unknown, origin = url, type = "application/json") => fetch(`${url}/api/projects/p${path}`, { method: "POST", headers: { origin, "content-type": type }, body: JSON.stringify(body) });
  const stop = async () => { if (child.exitCode === null) { const end = once(child, "exit"); child.kill(); await end; } };
  try {
    await serverUp(`${url}/api/projects`);
    const creation = { idea: { file: "notes/a.md", date: "2026-11-14" }, request_id: "same-click" };
    assert.equal((await post("/conversations", creation, "http://evil.example")).status, 403);
    assert.equal((await post("/conversations", creation, url, "text/plain")).status, 415);
    const created = await Promise.all([post("/conversations", creation), post("/conversations", creation)]);
    const sessions = await Promise.all(created.map(async (r) => (await r.json() as { result: SessionFile }).result));
    assert.equal(sessions[0]!.id, sessions[1]!.id);
    const view = await (await fetch(`${url}/api/projects/p/conversations/${sessions[0]!.id}`)).json() as { state: string; chat: unknown[] };
    assert.equal(view.state, "exited"); assert.equal(view.chat.length, 0);
    assert(!existsSync(fakeLog), "opening made no runtime request");
    assert.equal((await post("/conversations", { ...creation, idea: { file: "../a.md" }, request_id: "bad" })).status, 404);
    assert.equal((await post("/conversations", { ...creation, request_id: "mixed", queue: "HELD", step: "H1" })).status, 400);
    const selection = { file: "notes/a.md", dates: ["2026-11-14"], purpose: "plan", instruction: "Discuss only. Do not start work." };
    const preview = await (await post("/ideas/handoffs/preview", selection)).json() as { result: { revision: string; payload: string } };
    const request = { request_id: "send-once", revision: preview.result.revision, selection };
    assert.equal((await post("/ideas/handoffs", request, "http://evil.example")).status, 403);
    assert.equal((await post("/ideas/handoffs", request, url, "text/plain")).status, 415);
    writeFileSync(note, original.replace("Unanswered", "Changed question"));
    assert.equal((await post("/ideas/handoffs", request)).status, 409);
    writeFileSync(note, original);
    const results = await Promise.all([post("/ideas/handoffs", request), post("/ideas/handoffs", request)]);
    const handed = await Promise.all(results.map(async (r) => (await r.json() as { result: IdeaHandoff }).result));
    assert.equal(handed[0]!.state, "delivered"); assert.deepEqual(handed[0], handed[1]);
    assert.equal(handed[0]!.payload, preview.result.payload);
    await stop(); child = spawnServer({ ...env, NEXUS_PORT: String(port) }); await serverUp(`${url}/api/projects`);
    const again = await (await post("/ideas/handoffs", request)).json() as { result: IdeaHandoff };
    assert.deepEqual(again.result, handed[0]);
    assert.equal(store.readIdeaHandoffs().records.length, 1);
    const dest = again.result.delivery!;
    assert.equal(store.readInbox(dest.session).entries.filter((m) => m.id === dest.inbox).length, 1);
    assert.equal(store.readChat(dest.session).entries.filter((m) => m.message_id === dest.inbox).length, 1);
    assert.equal(readFileSync(note, "utf8"), original);
    assert.equal(readFileSync(join(store.dir, "queues/HELD/queue.yaml"), "utf8"), queue);
    assert.equal(store.readStart("HELD"), undefined); assert.equal(store.readRun("HELD"), undefined);
  } finally { await stop(); }
});
